#!/usr/bin/env python3
"""Write THIRD_PARTY_LICENSES.txt, or the game's Credits list: every crate built into a released build, with its licence.

Usage: tools/third_party.py [OUT]
       tools/third_party.py --credits [--check]

Walks `cargo metadata`'s normal (not build or dev) dependencies from every released build of the game and the card
editor, lists each crate with its licence and repository, then prints every licence or notice file those crates ship,
each distinct text once under the crates that carry it. Writes to stdout without OUT.

--credits writes crates/game/credits/crates.txt instead: the crates' names grouped by licence, which the Credits
screen shows. With --check it writes nothing and exits 1 if that file is out of date.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CREDITS = ROOT / 'crates/game/credits/crates.txt'
# Each released build: its target and the workspace packages it starts from.
GAME = ['last-harvest']
BUILDS = [
    ('aarch64-unknown-linux-gnu', GAME),
    ('x86_64-unknown-linux-gnu', GAME),
    ('aarch64-apple-darwin', GAME),
    ('x86_64-pc-windows-msvc', GAME),
    ('aarch64-pc-windows-msvc', GAME),
    ('aarch64-linux-android', GAME),
    ('wasm32-unknown-unknown', GAME + ['sprite-editor']),
]
LICENCE_FILE = re.compile(r'^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)', re.IGNORECASE)


def shipped():
    """The packages, by id, reachable through normal dependencies from any released build."""
    packages, found = {}, set()
    for target, roots in BUILDS:
        # Every feature, so the muOS build's SDL2 counts.
        cmd = ['cargo', 'metadata', '--locked', '--all-features', '--format-version', '1', '--filter-platform', target]
        meta = json.loads(subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout)
        packages.update((p['id'], p) for p in meta['packages'])
        nodes = {n['id']: n for n in meta['resolve']['nodes']}
        todo = [p['id'] for p in meta['packages'] if p['name'] in roots and p['id'] in meta['workspace_members']]
        seen = set()
        while todo:
            node = nodes[todo.pop()]
            for dep in node['deps']:
                if any(k['kind'] is None for k in dep['dep_kinds']) and dep['pkg'] not in seen:
                    seen.add(dep['pkg'])
                    todo.append(dep['pkg'])
        found |= seen
    workspace = {i for i, p in packages.items() if p['source'] is None}
    return sorted((packages[i] for i in found - workspace), key=lambda p: (p['name'], p['version']))


def licence_files(package):
    folder = Path(package['manifest_path']).parent
    return sorted(f for f in folder.iterdir() if f.is_file() and LICENCE_FILE.match(f.name))


def licence_name(expr):
    """`expr` with `/` read as OR and a plain OR list in one order, so equal choices group together."""
    if not expr:
        return 'Its own licence file'
    expr = expr.replace('/', ' OR ')
    if re.search(r'\bAND\b|\bWITH\b|[()]', expr):
        return ' '.join(expr.split())
    first = {'MIT': 0, 'Apache-2.0': 1}
    terms = sorted({t.strip() for t in expr.split(' OR ')}, key=lambda t: (first.get(t, 2), t))
    return ' OR '.join(terms)


def credits(crates):
    groups = {}
    for p in crates:
        groups.setdefault(licence_name(p['license']), set()).add(p['name'])
    out = ['# Generated by tools/third_party.py --credits: one licence per line, then the crates under it.']
    for name, members in sorted(groups.items(), key=lambda g: (-len(g[1]), g[0])):
        out.append(f"{name}: {', '.join(sorted(members))}")
    return '\n'.join(out) + '\n'


def write_credits(check):
    body = credits(shipped())
    if not check:
        CREDITS.write_text(body, encoding='utf-8')
    elif not CREDITS.exists() or CREDITS.read_text(encoding='utf-8') != body:
        sys.exit(f'{CREDITS.relative_to(ROOT)} is out of date: run tools/third_party.py --credits')


def main():
    if '--credits' in sys.argv:
        write_credits('--check' in sys.argv)
        return
    crates = shipped()
    texts, bare = {}, []
    for p in crates:
        files = licence_files(p)
        if not files:
            bare.append(p)
        for f in files:
            text = f.read_text(encoding='utf-8', errors='replace').strip()
            texts.setdefault(text, []).append(f"{p['name']} {p['version']} ({f.name})")
    width = max(len(f"{p['name']} {p['version']}") for p in crates)
    out = ['Last Harvest is MIT-licensed (see LICENSE). It is built with the crates below, under their own licences.',
           'Generated by tools/third_party.py.', '']
    out += [f"{p['name'] + ' ' + p['version']:<{width}}  {p['license'] or 'see its licence file'}  {p['repository'] or ''}".rstrip()
            for p in crates]
    if bare:
        out += ['', 'These crates ship no licence file; their licence is the standard text named above:']
        out += [f"  {p['name']} {p['version']}" for p in bare]
    for text, owners in texts.items():
        out += ['', '=' * 100, 'Used by: ' + ', '.join(owners), '=' * 100, '', text]
    body = '\n'.join(out) + '\n'
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(body, encoding='utf-8')
    else:
        sys.stdout.write(body)


if __name__ == '__main__':
    main()
