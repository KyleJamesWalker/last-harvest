#!/usr/bin/env python3
"""Write THIRD_PARTY_LICENSES.txt: every crate built into the released game and card editor, with its licence.

Usage: tools/third_party.py [OUT]

Walks `cargo metadata`'s normal (not build or dev) dependencies from the device binary and the two wasm builds, lists
each crate with its licence and repository, then prints every licence or notice file those crates ship, each distinct
text once under the crates that carry it. Writes to stdout without OUT.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Each released build: its target and the workspace packages it starts from.
BUILDS = [('aarch64-unknown-linux-gnu', ['last-harvest']), ('wasm32-unknown-unknown', ['last-harvest', 'sprite-editor'])]
LICENCE_FILE = re.compile(r'^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)', re.IGNORECASE)


def shipped():
    """The packages, by id, reachable through normal dependencies from any released build."""
    packages, found = {}, set()
    for target, roots in BUILDS:
        cmd = ['cargo', 'metadata', '--locked', '--format-version', '1', '--filter-platform', target]
        meta = json.loads(subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout)
        packages.update((p['id'], p) for p in meta['packages'])
        nodes = {n['id']: n for n in meta['resolve']['nodes']}
        todo = [p['id'] for p in meta['packages'] if p['name'] in roots and p['id'] in meta['workspace_members']]
        while todo:
            node = nodes[todo.pop()]
            for dep in node['deps']:
                if any(k['kind'] is None for k in dep['dep_kinds']) and dep['pkg'] not in found:
                    found.add(dep['pkg'])
                    todo.append(dep['pkg'])
    workspace = {i for i, p in packages.items() if p['source'] is None}
    return sorted((packages[i] for i in found - workspace), key=lambda p: (p['name'], p['version']))


def licence_files(package):
    folder = Path(package['manifest_path']).parent
    return sorted(f for f in folder.iterdir() if f.is_file() and LICENCE_FILE.match(f.name))


def main():
    crates = shipped()
    texts, bare = {}, []
    for p in crates:
        files = licence_files(p)
        if not files:
            bare.append(p)
        for f in files:
            text = f.read_text(errors='replace').strip()
            texts.setdefault(text, []).append(f"{p['name']} {p['version']} ({f.name})")
    width = max(len(f"{p['name']} {p['version']}") for p in crates)
    out = ['Last Harvest is MIT-licensed (see LICENSE). It is built with the crates below, under their own licences.',
           'Generated by tools/third_party.py.', '']
    out += [f"{p['name'] + ' ' + p['version']:<{width}}  {p['license'] or 'see its licence file'}  {p['repository'] or ''}".rstrip()
            for p in crates]
    if bare:
        out += ['', 'These crates ship no licence file; their licence is the standard text named above:']
        out += [f"  {p['name']} {p['version']}" for p in bare]
    for text, owners in texts.items():
        out += ['', '=' * 100, 'Used by: ' + ', '.join(owners), '=' * 100, '', text]
    body = '\n'.join(out) + '\n'
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(body)
    else:
        sys.stdout.write(body)


if __name__ == '__main__':
    main()
